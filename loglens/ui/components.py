"""Reusable page pieces. Any text that came from a log file is escaped before it is shown."""

from __future__ import annotations

import streamlit as st

from ..detection import SEVERITIES
from ..schema import describe_schema
from . import state
from .safe import escape_html

SEVERITY_EMOJI = {
    "critical": "\U0001f534",
    "high": "\U0001f7e0",
    "medium": "\U0001f7e1",
    "low": "\U0001f535",
}

EXAMPLE_CSV = """timestamp,source_ip,username,event_type,outcome,host,message
2026-03-02T09:14:02Z,192.0.2.14,alice.morgan,login,success,sso-01,Login succeeded
2026-03-02T09:15:40Z,203.0.113.45,svc.backup,login,failure,vpn-gw-01,Invalid password
2026-03-02T09:16:05Z,192.0.2.14,alice.morgan,access,denied,hr-portal-01,Access denied: hr/files"""

WELCOME_STEPS = (
    "Load the demo data, or upload a CSV in the sidebar",
    "LogLens validates the file and normalises times to UTC",
    "Four detection rules analyse the events",
    "Explore alerts and their evidence, filter, and export",
)


def severity_label(severity: str) -> str:
    """'3 - High' plus a colour marker.

    The leading rank makes the column sort in severity order when its header is clicked (a
    leading emoji would sort by code point: critical, low, high, medium). The word keeps it
    readable without relying on colour.
    """
    return f"{SEVERITIES.index(severity) + 1} - {severity.capitalize()} {SEVERITY_EMOJI[severity]}"


def severity_badge(severity: str) -> str:
    """HTML badge; ``severity`` is one of the four fixed values, never log content."""
    return f'<span class="ll-badge ll-badge-{severity}">{severity}</span>'


def plain_text(text: str) -> None:
    """A paragraph that may contain log content. Rendered as inert text: no markdown, no links."""
    st.html(f'<p class="ll-plain">{escape_html(text)}</p>')


def plain_list(items: list[str]) -> None:
    entries = "".join(f"<li>{escape_html(item)}</li>" for item in items)
    st.html(f'<ul class="ll-plain">{entries}</ul>')


def error_box(text: str) -> None:
    """Error banner for messages that may quote the uploaded file (name, header cells)."""
    st.html(f'<div class="ll-alert ll-alert-error" role="alert">{escape_html(text)}</div>')


def dataset_caption(dataset) -> None:
    kind = "Synthetic demo data" if dataset.is_demo else "Uploaded file"
    st.html(
        f'<div class="ll-sidecap"><b>{kind}:</b> {escape_html(dataset.label)}<br>'
        f"{len(dataset.events):,} events loaded</div>"
    )


def page_header(title: str, subtitle: str) -> None:
    st.markdown(
        f'<div class="ll-header"><h1>{escape_html(title)}</h1><p>{escape_html(subtitle)}</p></div>',
        unsafe_allow_html=True,
    )


def scope_bar(scope: state.Scope, *, note: str | None = None) -> None:
    """States exactly which data the numbers below describe, and any non-default settings."""
    total = len(scope.all_events)
    shown = len(scope.events)
    filters = scope.flt.describe()
    if filters:
        detail = " &middot; ".join(escape_html(part) for part in filters)
        headline = f"<b>{shown:,}</b> of {total:,} events match the filters"
    else:
        detail = '<span class="ll-dim">No filters applied</span>'
        headline = f"All <b>{total:,}</b> events"
    extra = f' <span class="ll-dim">&middot; {escape_html(note)}</span>' if note else ""
    changed = state.changed_settings(scope.config)
    if changed:
        detail += "<br><b>Detection settings changed:</b> " + escape_html("; ".join(changed))
    # st.html, not st.markdown: the filter text can quote usernames from the log (see safe.py).
    st.html(f'<div class="ll-scope"><b>Scope:</b> {headline}{extra}<br>{detail}</div>')
    if filters:
        st.button("Reset filters", key="reset_scope", on_click=state.reset_filters)


def dataset_notice(scope: state.Scope) -> None:
    if scope.dataset.is_demo:
        st.info(
            "**Synthetic demo data.** These events were generated by LogLens for demonstration. "
            "The accounts, IP addresses and incidents are made up and are not real findings.",
            icon=":material/science:",
        )


def heuristic_note() -> None:
    st.caption(
        "Alerts are **heuristic flags** from simple threshold rules, not confirmed incidents. "
        "Each one needs analyst review; harmless activity can trigger every rule."
    )


def severity_cards(counts: dict[str, int]) -> None:
    columns = st.columns(len(SEVERITIES))
    for column, severity in zip(columns, reversed(SEVERITIES), strict=True):
        with column:
            st.markdown(
                f'<div class="ll-sev ll-sev-{severity}"><div class="ll-l">{severity} alerts</div>'
                f'<div class="ll-n">{counts[severity]:,}</div></div>',
                unsafe_allow_html=True,
            )


def schema_table() -> None:
    """The column reference as a wrapping table (a data grid would truncate the descriptions)."""
    lines = ["| Column | Required | Meaning |", "|---|---|---|"]
    lines += [
        f"| `{row['column']}` | {row['required']} | {row['description']} |"
        for row in describe_schema()
    ]
    st.markdown("\n".join(lines))  # static schema text only


def no_results(message: str) -> None:
    st.info(message, icon=":material/filter_alt_off:")
    st.button("Reset filters", key="reset_empty", on_click=state.reset_filters)


def welcome() -> None:
    """Landing screen shown until data is loaded."""
    page_header(
        "Welcome to LogLens",
        "A local security log analyzer: upload logs, spot suspicious patterns, and see exactly "
        "why each one was flagged.",
    )
    left, right = st.columns([3, 2], gap="large")
    with left, st.container(border=True):
        st.markdown("#### Get started")
        steps = "<br>".join(
            f"<span class='ll-step'>{number}.</span> {text}"
            for number, text in enumerate(WELCOME_STEPS, start=1)
        )
        st.markdown(steps, unsafe_allow_html=True)  # static text only
        st.button(
            "Load demo data",
            type="primary",
            icon=":material/science:",
            on_click=state.load_demo,
            key="welcome_demo",
        )
        st.caption(
            "The demo dataset is entirely synthetic: made-up accounts, documentation-range "
            "IP addresses, and scripted scenarios. It is not real security data."
        )
    with right, st.container(border=True):
        st.markdown("#### Your data stays with you")
        st.markdown(
            "- Files are processed locally in memory\n"
            "- Your log data is never sent to any external service\n"
            "- Nothing is saved to disk unless you export it\n"
            "- Closing or reloading the tab ends the session; its data is discarded from memory "
            "within about two minutes"
        )
    with st.expander("Supported CSV format", expanded=False):
        schema_table()
        st.code(EXAMPLE_CSV, language="csv")
        st.caption("Maximum upload size: 25 MB. Comma-separated, UTF-8, one event per row.")
    heuristic_note()


def show_load_error() -> None:
    """Why the last upload was refused (shown once, above whichever page is open)."""
    error = state.load_error_message()
    if error:
        error_box(error)


def require_scope() -> state.Scope | None:
    """The current scope, or render the welcome screen and return ``None``."""
    scope = state.build_scope()
    if scope is None:
        welcome()
        return None
    return scope
